# MAJOR 4 correction: `alembic check` must compare server_default drift, not
# just column type/presence. backend/alembic/env.py now sets
# compare_server_default=True in both context.configure() calls (online and
# offline). Each test below is a negative control in the same spirit as
# test_a_genuine_drift_is_actually_detected above: without that setting,
# `alembic check` reports "No new upgrade operations detected" for all three
# of these - a real, exploitable blind spot (see admins.is_active, which
# app/models/admin.py deliberately gives only a client-side default=True,
# never a server_default - see app/core/schema_introspect.py's callers,
# which both rely on that distinction being real).
# ---------------------------------------------------------------------------


def test_adding_a_server_default_outside_a_migration_is_detected(migrated_stage2_database):
    """admins.is_active has no server_default in current metadata (it's a
    client-side SQLAlchemy default - see app/models/admin.py). Adding one
    directly against the live database is genuine drift and must be caught."""
    from sqlalchemy import create_engine, text

    cfg = migrated_stage2_database
    url = cfg.get_main_option("sqlalchemy.url")
    engine = create_engine(url)
    try:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE admins ALTER COLUMN is_active SET DEFAULT true"))
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(cfg)
    finally:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE admins ALTER COLUMN is_active DROP DEFAULT"))
        engine.dispose()


def test_removing_a_server_default_outside_a_migration_is_detected(migrated_stage2_database):
    """Opposite direction: admins.created_at DOES have a server_default
    (func.now()) in current metadata. Removing it directly against the live
    database must also be caught, not just additions."""
    from sqlalchemy import create_engine, text

    cfg = migrated_stage2_database
    url = cfg.get_main_option("sqlalchemy.url")
    engine = create_engine(url)
    try:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE admins ALTER COLUMN created_at DROP DEFAULT"))
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(cfg)
    finally:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE admins ALTER COLUMN created_at SET DEFAULT now()"))
        engine.dispose()


def test_changing_a_server_default_outside_a_migration_is_detected(migrated_stage2_database):
    """Proves the check compares default *content*, not just presence/
    absence: admins.updated_at already has a server_default in current
    metadata (func.now()) - replacing it with a different-but-still-present
    default must still be flagged as drift."""
    from sqlalchemy import create_engine, text

    cfg = migrated_stage2_database
    url = cfg.get_main_option("sqlalchemy.url")
    engine = create_engine(url)
    try:
        with engine.begin() as conn:
            conn.execute(
                text("ALTER TABLE admins ALTER COLUMN updated_at SET DEFAULT '2000-01-01 00:00:00+00'")
            )
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(cfg)
    finally:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE admins ALTER COLUMN updated_at SET DEFAULT now()"))
        engine.dispose()
