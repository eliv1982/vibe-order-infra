"""Stage 2, schema drift check (see the Stage 2 spec, section 14).

Uses Alembic's own `alembic check` machinery (`alembic.command.check`,
available since Alembic 1.13 - see backend/pyproject.toml's
`alembic>=1.18,<1.19` pin) via its autogenerate comparison against a
database freshly migrated to head. This is not a tautological test: `check`
independently reflects the *live* database and diffs it against
`Base.metadata` (backend/app/core/db_base.py) using the same comparators
`alembic revision --autogenerate` would use - a genuine divergence between
what the migrations produce and what the current SQLAlchemy models declare
raises `alembic.util.exc.AutogenerateDiffsDetected`.

Requires TEST_DATABASE_URL with CREATEDB+CREATEROLE rights - see
tests/stage2_db_helpers.py's module docstring.
"""

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from app.db_admin.bootstrap_roles import bootstrap_roles
from tests import stage2_db_helpers as h

pytestmark = pytest.mark.skipif(
    not h.TEST_DATABASE_URL,
    reason="TEST_DATABASE_URL is not set - skipping PostgreSQL integration tests",
)


@pytest.fixture()
def migrated_stage2_database():
    name = h.disposable_database_name("drift")
    h.create_disposable_database(name)
    bootstrap_roles(h.role_bootstrap_config(name))
    cfg = h.alembic_config_for(h.migration_database_url(name))
    command.upgrade(cfg, "head")
    try:
        yield cfg
    finally:
        h.drop_disposable_database(name)


def test_migration_head_matches_current_sqlalchemy_metadata(migrated_stage2_database):
    """`alembic check` must find nothing to generate - if it raises, either a
    model changed without a matching migration, or a migration doesn't
    actually produce what the model declares. Either way, that's real
    drift, not a false positive: this ran against a database that was *just*
    migrated to head by this same test, using the *current* models module
    (backend/app/core/db_base.py's Base.metadata)."""
    command.check(migrated_stage2_database)


def test_a_genuine_drift_is_actually_detected(migrated_stage2_database, monkeypatch):
    """Negative control: if this test ever failed to raise, that would mean
    `alembic check` above is a tautology (e.g. broken metadata wiring) and
    the previous test's pass would be meaningless. Introduces a real,
    deliberate divergence - a column current models don't have - directly
    against the live database, then confirms `alembic check` catches it."""
    from sqlalchemy import create_engine, text

    cfg = migrated_stage2_database
    url = cfg.get_main_option("sqlalchemy.url")
    engine = create_engine(url)
    try:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE applications ADD COLUMN drift_test_column INTEGER"))
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(cfg)
    finally:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE applications DROP COLUMN drift_test_column"))
        engine.dispose()


